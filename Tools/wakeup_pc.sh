#!/bin/bash

# 定义目标电脑的 MAC 地址
MAC_ADDRESS="<REDACTED-填实际MAC>"

echo "========================================="
echo " 正在发送 Wake-on-LAN 唤醒信号..."
echo " 目标 MAC: $MAC_ADDRESS"
echo "========================================="

# 执行 wol 命令
wol $MAC_ADDRESS

# 检查命令是否执行成功
if [ $? -eq 0 ]; then
    echo "-----------------------------------------"
    echo " [成功] 唤醒信号已发送！电脑正在开机..."
    echo "========================================="
else
    echo "-----------------------------------------"
    echo " [错误] 信号发送失败，请检查网络或 wol 工具。"
    echo "========================================="
fi
